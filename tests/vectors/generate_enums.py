"""Writes tests/src/test_enums.adb: every generated enumeration against
pymavlink, an independent implementation (make vectors-enums).

For each enum in definitions/common.xml it first checks that pymavlink's
module-level constants agree with the XML's entry values, then writes Ada
checks: To_ returns the named literal for every value and Is_Known_ rejects
values outside the set; a flag record sets exactly its own bit for every
entry and From_/To_ round-trip single-bit, all-bits and mixed wire values.
Only pymavlink's constants are used; no pymavlink code is part of the
library.
"""

import os
import sys
from pathlib import Path

os.environ["MAVLINK20"] = "1"

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "generator"))

import adamavlink_gen as gen  # noqa: E402
from pymavlink.dialects.v20 import common as m  # noqa: E402


def check_against_pymavlink(enums):
    for enum in enums.values():
        for name, value in enum.entries:
            if not hasattr(m, name):
                raise SystemExit(f"{enum.name}: {name} missing from pymavlink")
            if getattr(m, name) != value:
                raise SystemExit(
                    f"{enum.name}.{name}: XML {value}, pymavlink "
                    f"{getattr(m, name)}"
                )


def plain_case(enum):
    lines = [f"   --  {enum.name}"]
    checks = []
    for (name, value), literal in zip(enum.entries, enum.literals):
        checks.append(
            f'      Check (To_{enum.ada_name} ({value}) = {literal}, '
            f'"{enum.name} {value}");'
        )
    width_max = {"Unsigned_8": 255, "Unsigned_16": 65535,
                 "Unsigned_32": 2**32 - 1}[enum.width]
    values = [v for _, v in enum.entries]
    probes = []
    if max(values) < width_max:
        probes.append(max(values) + 1)
    if 0 not in values:
        probes.append(0)
    for probe in probes:
        checks.append(
            f"      Check (not Is_Known_{enum.ada_name} ({probe}), "
            f'"{enum.name} rejects {probe}");'
        )
    lines += checks
    return lines, len(checks)


def flag_case(enum):
    values = [v for _, v in enum.entries]
    lines = [f"   --  {enum.name}"]
    checks = []
    for name, value in enum.entries:
        component = gen.flag_component(enum.name, name)
        checks.append(
            f"      Check (To_{enum.ada_name} ({value}).{component}, "
            f'"{enum.name} {name}");'
        )
        checks.append(
            f"      Check (From_{enum.ada_name} (To_{enum.ada_name} ({value}))"
            f" = {value}, \"{enum.name} round-trips {value}\");"
        )
    probes = [0, sum(values)]  # empty and all-bits wire values
    mixed = sum(v for i, v in enumerate(values) if i % 2 == 0)
    if mixed not in probes:
        probes.append(mixed)
    for probe in dict.fromkeys(probes):
        checks.append(
            f"      Check (From_{enum.ada_name} (To_{enum.ada_name} ({probe}))"
            f" = {probe}, \"{enum.name} round-trips {probe}\");"
        )
    lines += checks
    return lines, len(checks)


def main():
    _messages, enums = gen.read_definitions(ROOT / "definitions" / "common.xml")
    check_against_pymavlink(enums)
    cases, total = [], 0
    for enum in sorted(enums.values(), key=lambda e: e.name):
        if enum.is_plain:
            lines, n = plain_case(enum)
        else:
            lines, n = flag_case(enum)
        cases.append("\n".join(lines))
        total += n
    text = f"""--  Generated by tests/vectors/generate_enums.py with pymavlink
--  (make vectors-enums). Do not edit.

with Ada.Text_IO;
with Interfaces;     use Interfaces;
with MAVLink.Enums;  use MAVLink.Enums;

--  Every generated enumeration against the values pymavlink publishes:
--  To_ names each value, Is_Known_ rejects the rest, and flag records
--  round-trip their wire values.
procedure Test_Enums is

   procedure Check (Condition : Boolean; Message : String) is
   begin
      if not Condition then
         raise Program_Error with Message;
      end if;
   end Check;

begin
{chr(10).join(cases)}
   Ada.Text_IO.Put_Line ("{total} enum checks match pymavlink");
end Test_Enums;
"""
    out = ROOT / "tests" / "src" / "test_enums.adb"
    out.write_text(text, newline="\n")
    print(f"{total} enum checks written to {out}")


if __name__ == "__main__":
    main()

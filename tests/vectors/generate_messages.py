"""Writes tests/src/test_messages.adb: every generated message against
pymavlink, an independent implementation (make vectors-messages).

For each message in generator/messages.txt it fills every field with
deterministic pseudo-random values, has pymavlink encode the frame, and
writes an Ada check that Pack + Encode give the same bytes and that Push +
Unpack give the same content back. It first checks that the generator's
CRC_EXTRA and payload length agree with pymavlink's. Only pymavlink's
output is used; no pymavlink code is part of the library.
"""

import os
import random
import struct
import sys
from pathlib import Path

os.environ["MAVLINK20"] = "1"

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "generator"))

import adamavlink_gen as gen  # noqa: E402
from pymavlink.dialects.v20 import common as m  # noqa: E402


class Sink:
    def __init__(self):
        self.data = b""

    def write(self, data):
        self.data += data


def value(rng, field):
    """A random value for one element: (Python value for pymavlink, Ada
    literal)."""
    t = field.crc_type
    if t in ("float", "double"):
        if t == "float":
            x = struct.unpack("<f", struct.pack("<f", rng.uniform(-1e4, 1e4)))[0]
            bits = struct.unpack("<I", struct.pack("<f", x))[0]
            return x, "16#%08X#" % bits
        x = rng.uniform(-1e6, 1e6)
        bits = struct.unpack("<Q", struct.pack("<d", x))[0]
        return x, "16#%016X#" % bits
    if t == "char":
        x = rng.randint(0x21, 0x7E)
        return x, str(x)
    size = field.size * 8
    if t.startswith("u"):
        x = rng.randint(1, 2**size - 1)
    else:
        x = rng.randint(-(2 ** (size - 1)) + 1, 2 ** (size - 1) - 1)
    return x, str(x) if x >= 0 else f"({x})"


def case(rng, message, sequence):
    cls = getattr(m, "MAVLink_" + message.name.lower() + "_message")
    if cls.crc_extra != message.crc_extra:
        raise SystemExit(f"{message.name}: CRC_EXTRA {message.crc_extra}, pymavlink {cls.crc_extra}")
    if cls.unpacker.size != message.length:
        raise SystemExit(f"{message.name}: length {message.length}, pymavlink {cls.unpacker.size}")

    args, ada = [], []
    for f in message.fields:  # pymavlink takes them in definition order
        if f.count:
            values = [value(rng, f) for _ in range(f.count)]
            if f.crc_type == "char":
                args.append(bytes(v for v, _ in values))
            else:
                args.append([v for v, _ in values])
            ada.append(f"{f.ada_name} => [{', '.join(a for _, a in values)}]")
        else:
            v, a = value(rng, f)
            args.append(v)
            ada.append(f"{f.ada_name} => {a}")

    sink = Sink()
    mav = m.MAVLink(sink, srcSystem=1, srcComponent=1)
    mav.seq = sequence
    mav.send(cls(*args))
    frame = ", ".join("16#%02X#" % b for b in sink.data)
    pkg = message.package
    return f"""
   --  {message.name}
   declare
      use type {pkg}.Content;
      C : constant {pkg}.Content :=
        ({", ".join(ada)});
      Expected : constant Byte_Array (1 .. {len(sink.data)}) :=
        [{frame}];
   begin
      Encode
        ((Sequence => {sequence}, System => 1, Component => 1, Id => {pkg}.Id,
          Compat_Flags => 0),
         {pkg}.Pack (C), Frame, Last);
      Check (Frame (1 .. Last) = Expected, "{message.name} encodes as pymavlink");
      Check (Feed (Expected) = Message_Ready, "{message.name} parses");
      Check ({pkg}.Unpack (Received (P)) = C, "{message.name} unpacks");
   end;
"""


def main():
    messages = gen.read_messages(ROOT / "definitions" / "common.xml")
    names = gen.read_selection(ROOT / "generator" / "messages.txt")
    rng = random.Random(20261120)
    cases = [case(rng, messages[n], i % 256) for i, n in enumerate(names)]
    withs = "\n".join(f"with {messages[n].package};" for n in names)
    text = f"""--  Generated by tests/vectors/generate_messages.py with pymavlink
--  (make vectors-messages). Do not edit.

with Ada.Text_IO;
with Interfaces;     use Interfaces;
with MAVLink;        use MAVLink;
with MAVLink.Frames; use MAVLink.Frames;
{withs}

--  Every generated message against frames encoded by pymavlink: Pack and
--  Encode give pymavlink's bytes, and Push and Unpack give the content back.
procedure Test_Messages is
   P     : Parser;
   Frame : Frame_Bytes;
   Last  : Frame_Size;

   procedure Check (Condition : Boolean; Message : String) is
   begin
      if not Condition then
         raise Program_Error with Message;
      end if;
   end Check;

   function Feed (Bytes : Byte_Array) return Event is
      Result : Event := None;
   begin
      for B of Bytes loop
         Push (P, B, Result);
      end loop;
      return Result;
   end Feed;
begin
{"".join(cases)}
   Ada.Text_IO.Put_Line ("{len(cases)} generated messages match pymavlink");
end Test_Messages;
"""
    out = ROOT / "tests" / "src" / "test_messages.adb"
    out.write_text(text, newline="\n")
    print(f"{len(cases)} message cases written to {out}")


if __name__ == "__main__":
    main()
